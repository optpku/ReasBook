const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../docs/app.js'), 'utf8');
const names = ['itemLocation', 'renderQueue', 'pollReviews', 'inProofRoute', 'updateTypeFilter'];
const helpers = names.map(name => {
  const start = source.search(new RegExp(`  (?:async )?function ${name}\\(`));
  const rest = source.slice(start + 1);
  const next = rest.search(/\n  (?:async )?function /);
  assert.ok(start >= 0 && next >= 0);
  return source.slice(start, start + 1 + next);
}).join('\n');
const element = () => ({textContent: '', innerHTML: '', attributes: {}, setAttribute(k, v) { this.attributes[k] = v; }});
const state = {selectedSlug: 'demo', bookRequest: 1, bookLoadState: 'loading'};
const refs = {itemResultCount: element(), reviewQueue: element()};
let fetches = 0;
const context = vm.createContext({state, refs, api: async () => {fetches++; return {};}, setSync: () => {throw new Error('must not sync before book loads');}});
vm.runInContext(helpers, context);
assert.deepEqual(Array.from(context.itemLocation({sourcePath: 'theorem_2_1_2.lean', section: 'section-2'})), ['Section 2']);
assert.deepEqual(Array.from(context.itemLocation({sourcePath: 'theorem_3_1_1.lean', section: 'section-3'})), ['Section 3']);
assert.deepEqual(Array.from(context.itemLocation({sourcePath: 'Chap02/section01_part2.lean', section: 'chapter-2'})), ['Chapter 2', 'Section 1', 'Part 2']);
state.proofRoute = 'v21';
assert.equal(context.inProofRoute({sourcePath: 'DFPWolfe/V21/Main.lean'}), true);
assert.equal(context.inProofRoute({moduleName: 'DFPWolfe.Main'}), false);
state.proofRoute = 'original';
assert.equal(context.inProofRoute({moduleName: 'DFPWolfe.V21.Main'}), false);
assert.equal(context.inProofRoute({moduleName: 'DFPWolfe.Main'}), true);
state.items = [1, 10, 11, 2].map(number => ({kind: 'theorem', section: `section-${number}`}));
state.itemTypeFilter = state.itemSectionFilter = 'all';
refs.itemTypeFilter = element(); refs.itemSectionFilter = element();
context.escapeHtml = String;
context.itemKind = () => 'Theorem';
context.updateTypeFilter();
assert.ok(refs.itemSectionFilter.innerHTML.indexOf('section-2') < refs.itemSectionFilter.innerHTML.indexOf('section-10'));
context.renderQueue();
assert.equal(refs.reviewQueue.attributes['aria-busy'], 'true');
assert.match(refs.itemResultCount.textContent, /Loading/);
assert.ok(!refs.reviewQueue.innerHTML.includes('No declarations match'));
(async () => {
  await context.pollReviews();
  assert.equal(fetches, 0);
  state.bookLoadState = 'error';
  context.renderQueue();
  assert.match(refs.itemResultCount.textContent, /unavailable/);
  await context.pollReviews();
  assert.equal(fetches, 0);
  // A review request already in flight must not overwrite a later book error.
  let finish;
  context.api = () => new Promise(resolve => {finish = resolve;});
  state.bookLoadState = 'ready';
  const pending = context.pollReviews();
  state.bookLoadState = 'error';
  finish({reviews: []});
  await pending;
  console.log('Loading and chapter navigation regression passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
